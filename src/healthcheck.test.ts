import { healthcheckHandler } from './healthcheck.js';
import { Status } from './index.js';
import { cacheConnection } from './checks/cache.js';
import { cpuCheck } from './checks/cpu.js';
import { dbConnection } from './checks/db.js';
import { disk } from './checks/disk.js';
import { egress } from './checks/egress.js';
import { memoryCheck } from './checks/memory.js';

jest.mock('./checks/cache.js');
jest.mock('./checks/cpu.js');
jest.mock('./checks/db.js');
jest.mock('./checks/disk.js');
jest.mock('./checks/egress.js');
jest.mock('./checks/memory.js');

describe('healthcheckHandler', () => {
  beforeEach(() => {
    jest.clearAllMocks();
  });

  describe('JSON response', () => {
    it('should return JSON response when accept header is not text/html', async () => {
      (memoryCheck as jest.Mock).mockResolvedValue({
        componentName: 'memory',
        status: Status.pass,
        message: 'Memory usage is below 80%',
        value: '50.00%',
        time: 10,
      });

      const result = await healthcheckHandler(
        { accept: 'application/json' },
        {
          checks: {
            memory_usage: true,
          },
        }
      );

      expect(result.type).toBe('application/json');
      expect(JSON.parse(result.body)).toEqual({
        status: Status.pass,
        description: 'Health check response, generated by allgood.',
        results: {
          memory_usage: {
            componentName: 'memory',
            status: Status.pass,
            message: 'Memory usage is below 80%',
            value: '50.00%',
            time: 10,
          },
        },
      });
    });

    it('should return JSON response when accept header is undefined', async () => {
      (cpuCheck as jest.Mock).mockResolvedValue({
        componentName: 'cpu',
        status: Status.pass,
        message: 'CPU usage is below 80%',
        value: '30.00%',
        time: 5,
      });

      const result = await healthcheckHandler(
        {},
        {
          checks: {
            cpu_usage: true,
          },
        }
      );

      expect(result.type).toBe('application/json');
      const body = JSON.parse(result.body);
      expect(body.status).toBe(Status.pass);
      expect(body.results.cpu_usage).toBeDefined();
    });

    it('should return fail status when any check fails', async () => {
      (memoryCheck as jest.Mock).mockResolvedValue({
        componentName: 'memory',
        status: Status.fail,
        message: 'Memory usage is above 80%',
        value: '90.00%',
        time: 10,
      });
      (cpuCheck as jest.Mock).mockResolvedValue({
        componentName: 'cpu',
        status: Status.pass,
        message: 'CPU usage is below 80%',
        value: '30.00%',
        time: 5,
      });

      const result = await healthcheckHandler(
        { accept: 'application/json' },
        {
          checks: {
            memory_usage: true,
            cpu_usage: true,
          },
        }
      );

      const body = JSON.parse(result.body);
      expect(body.status).toBe(Status.fail);
    });

    it('should return warn status when any check warns', async () => {
      (memoryCheck as jest.Mock).mockResolvedValue({
        componentName: 'memory',
        status: Status.warn,
        message: 'Memory usage is at warning level',
        value: '75.00%',
        time: 10,
      });
      (cpuCheck as jest.Mock).mockResolvedValue({
        componentName: 'cpu',
        status: Status.pass,
        message: 'CPU usage is below 80%',
        value: '30.00%',
        time: 5,
      });

      const result = await healthcheckHandler(
        { accept: 'application/json' },
        {
          checks: {
            memory_usage: true,
            cpu_usage: true,
          },
        }
      );

      const body = JSON.parse(result.body);
      expect(body.status).toBe(Status.warn);
    });
  });

  describe('HTML response', () => {
    it('should return HTML response when accept header includes text/html', async () => {
      (memoryCheck as jest.Mock).mockResolvedValue({
        componentName: 'memory',
        status: Status.pass,
        message: 'Memory usage is below 80%',
        value: '50.00%',
        time: 10,
      });

      const result = await healthcheckHandler(
        { accept: 'text/html' },
        {
          checks: {
            memory_usage: true,
          },
        }
      );

      expect(result.type).toBe('text/html');
      expect(result.body).toContain('<!DOCTYPE html>');
      expect(result.body).toContain('Health Check');
      expect(result.body).toContain("👌 It's All Good");
      expect(result.body).toContain('#4CAF50');
    });

    it('should display fail banner when any check fails', async () => {
      (memoryCheck as jest.Mock).mockResolvedValue({
        componentName: 'memory',
        status: Status.fail,
        message: 'Memory usage is above 80%',
        value: '90.00%',
        time: 10,
      });

      const result = await healthcheckHandler(
        { accept: 'text/html' },
        {
          checks: {
            memory_usage: true,
          },
        }
      );

      expect(result.body).toContain("❌ Something's Wrong");
      expect(result.body).toContain('#F44336');
    });

    it('should display warn banner when any check warns', async () => {
      (memoryCheck as jest.Mock).mockResolvedValue({
        componentName: 'memory',
        status: Status.warn,
        message: 'Memory usage is at warning level',
        value: '75.00%',
        time: 10,
      });

      const result = await healthcheckHandler(
        { accept: 'text/html' },
        {
          checks: {
            memory_usage: true,
          },
        }
      );

      expect(result.body).toContain("❌ Something's Wrong");
      expect(result.body).toContain('#FFC107');
    });

    it('should display check results with icons', async () => {
      (memoryCheck as jest.Mock).mockResolvedValue({
        componentName: 'memory',
        status: Status.pass,
        message: 'Memory usage is below 80%',
        value: '50.00%',
        time: 10,
      });

      const result = await healthcheckHandler(
        { accept: 'text/html' },
        {
          checks: {
            memory_usage: true,
          },
        }
      );

      expect(result.body).toContain('✅');
      expect(result.body).toContain('Memory usage is below 80%');
      expect(result.body).toContain('(50.00%)');
      expect(result.body).toContain('[10ms]');
    });

    it('should not display value when it is "true" or "false"', async () => {
      (cacheConnection as jest.Mock).mockResolvedValue({
        componentName: 'cache_connection',
        status: Status.pass,
        message: 'Cache connection successful',
        value: 'true',
        time: 20,
      });

      const result = await healthcheckHandler(
        { accept: 'text/html' },
        {
          checks: {
            cache_connection: true,
          },
        }
      );

      expect(result.body).toContain('Cache connection successful');
      expect(result.body).not.toContain('(true)');
    });

    it('should sort check results alphabetically', async () => {
      (memoryCheck as jest.Mock).mockResolvedValue({
        componentName: 'memory',
        status: Status.pass,
        message: 'Memory check',
        value: '50.00%',
        time: 10,
      });
      (cpuCheck as jest.Mock).mockResolvedValue({
        componentName: 'cpu',
        status: Status.pass,
        message: 'CPU check',
        value: '30.00%',
        time: 5,
      });
      (disk as jest.Mock).mockResolvedValue({
        componentName: 'disk',
        status: Status.pass,
        message: 'Disk check',
        value: '40.00%',
        time: 8,
      });

      const result = await healthcheckHandler(
        { accept: 'text/html' },
        {
          checks: {
            memory_usage: true,
            cpu_usage: true,
            disk_space: true,
          },
        }
      );

      const cpuIndex = result.body.indexOf('CPU check');
      const diskIndex = result.body.indexOf('Disk check');
      const memoryIndex = result.body.indexOf('Memory check');

      expect(cpuIndex).toBeLessThan(diskIndex);
      expect(diskIndex).toBeLessThan(memoryIndex);
    });
  });

  describe('multiple checks', () => {
    it('should execute all enabled checks', async () => {
      (memoryCheck as jest.Mock).mockResolvedValue({
        componentName: 'memory',
        status: Status.pass,
        message: 'Memory OK',
        value: '50%',
        time: 10,
      });
      (cpuCheck as jest.Mock).mockResolvedValue({
        componentName: 'cpu',
        status: Status.pass,
        message: 'CPU OK',
        value: '30%',
        time: 5,
      });
      (disk as jest.Mock).mockResolvedValue({
        componentName: 'disk',
        status: Status.pass,
        message: 'Disk OK',
        value: '40%',
        time: 8,
      });
      (cacheConnection as jest.Mock).mockResolvedValue({
        componentName: 'cache',
        status: Status.pass,
        message: 'Cache OK',
        value: 'true',
        time: 15,
      });
      (dbConnection as jest.Mock).mockResolvedValue({
        componentName: 'db',
        status: Status.pass,
        message: 'DB OK',
        value: 'true',
        time: 20,
      });
      (egress as jest.Mock).mockResolvedValue({
        componentName: 'egress',
        status: Status.pass,
        message: 'Egress OK',
        value: 'true',
        time: 25,
      });

      const result = await healthcheckHandler(
        { accept: 'application/json' },
        {
          checks: {
            memory_usage: true,
            cpu_usage: true,
            disk_space: true,
            cache_connection: true,
            db_connection: true,
            outbound_internet: true,
          },
        }
      );

      expect(memoryCheck).toHaveBeenCalled();
      expect(cpuCheck).toHaveBeenCalled();
      expect(disk).toHaveBeenCalled();
      expect(cacheConnection).toHaveBeenCalled();
      expect(dbConnection).toHaveBeenCalled();
      expect(egress).toHaveBeenCalled();

      const body = JSON.parse(result.body);
      expect(Object.keys(body.results)).toHaveLength(6);
    });

    it('should skip disabled checks', async () => {
      (memoryCheck as jest.Mock).mockResolvedValue({
        componentName: 'memory',
        status: Status.pass,
        message: 'Memory OK',
        value: '50%',
        time: 10,
      });

      const result = await healthcheckHandler(
        { accept: 'application/json' },
        {
          checks: {
            memory_usage: true,
            cpu_usage: false,
            disk_space: false,
          },
        }
      );

      expect(memoryCheck).toHaveBeenCalled();
      expect(cpuCheck).not.toHaveBeenCalled();
      expect(disk).not.toHaveBeenCalled();

      const body = JSON.parse(result.body);
      expect(Object.keys(body.results)).toHaveLength(1);
    });

    it('should handle empty checks config', async () => {
      const result = await healthcheckHandler(
        { accept: 'application/json' },
        {
          checks: {},
        }
      );

      const body = JSON.parse(result.body);
      expect(body.status).toBe(Status.pass);
      expect(body.results).toEqual({});
    });
  });

  describe('edge cases', () => {
    it('should handle checks running in parallel', async () => {
      let callOrder: string[] = [];
      
      (memoryCheck as jest.Mock).mockImplementation(async () => {
        await new Promise(resolve => setTimeout(resolve, 50));
        callOrder.push('memory');
        return {
          componentName: 'memory',
          status: Status.pass,
          message: 'Memory OK',
          value: '50%',
          time: 50,
        };
      });
      
      (cpuCheck as jest.Mock).mockImplementation(async () => {
        await new Promise(resolve => setTimeout(resolve, 10));
        callOrder.push('cpu');
        return {
          componentName: 'cpu',
          status: Status.pass,
          message: 'CPU OK',
          value: '30%',
          time: 10,
        };
      });

      await healthcheckHandler(
        { accept: 'application/json' },
        {
          checks: {
            memory_usage: true,
            cpu_usage: true,
          },
        }
      );

      // CPU should finish before memory due to parallel execution
      expect(callOrder[0]).toBe('cpu');
      expect(callOrder[1]).toBe('memory');
    });

    it('should handle unknown check names gracefully', async () => {
      const result = await healthcheckHandler(
        { accept: 'application/json' },
        {
          checks: {
            // @ts-expect-error Testing unknown check name
            unknown_check: true,
          },
        }
      );

      const body = JSON.parse(result.body);
      expect(body.results).toEqual({});
    });
  });
});