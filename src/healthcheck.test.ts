import { healthcheckHandler } from './healthcheck.js';
import { cacheConnection } from './checks/cache.js';
import { cpuCheck } from './checks/cpu.js';
import { dbConnection } from './checks/db.js';
import { disk } from './checks/disk.js';
import { egress } from './checks/egress.js';
import { memoryCheck } from './checks/memory.js';
import { Status, type Config } from './index.js';

jest.mock('./checks/cache.js', () => ({
  cacheConnection: jest.fn(),
}));

jest.mock('./checks/cpu.js', () => ({
  cpuCheck: jest.fn(),
}));

jest.mock('./checks/db.js', () => ({
  dbConnection: jest.fn(),
}));

jest.mock('./checks/disk.js', () => ({
  disk: jest.fn(),
}));

jest.mock('./checks/egress.js', () => ({
  egress: jest.fn(),
}));

jest.mock('./checks/memory.js', () => ({
  memoryCheck: jest.fn(),
}));

describe('healthcheckHandler', () => {
  const passResult = (componentName: string, message = 'All good') => ({
    componentName,
    status: Status.pass,
    message,
    value: 'true',
    time: 5,
  });

  const failResult = (componentName: string, message = 'Something failed') => ({
    componentName,
    status: Status.fail,
    message,
    value: 'false',
    time: 10,
  });

  const warnResult = (componentName: string, message = 'Warning issued') => ({
    componentName,
    status: Status.warn,
    message,
    value: '75%',
    time: 8,
  });

  beforeEach(() => {
    jest.clearAllMocks();

    (memoryCheck as jest.Mock).mockResolvedValue(passResult('memory_usage'));
    (egress as jest.Mock).mockResolvedValue(passResult('outbound_internet'));
    (disk as jest.Mock).mockResolvedValue(passResult('disk_space'));
    (cacheConnection as jest.Mock).mockResolvedValue(passResult('cache_connection'));
    (dbConnection as jest.Mock).mockResolvedValue(passResult('db_connection'));
    (cpuCheck as jest.Mock).mockResolvedValue(passResult('cpu_usage'));
  });

  const baseConfig: Config = {
    checks: {
      memory_usage: true,
      outbound_internet: true,
      disk_space: true,
      cache_connection: true,
      db_connection: true,
      cpu_usage: true,
    },
  } as unknown as Config;

  it('should return a JSON response with status pass when all checks pass', async () => {
    const result = await healthcheckHandler({}, baseConfig);

    expect(result.type).toBe('application/json');
    const body = JSON.parse(result.body);
    expect(body.status).toBe(Status.pass);
    expect(body.description).toBe('Health check response, generated by allgood.');
    expect(Object.keys(body.results)).toEqual(
      expect.arrayContaining([
        'memory_usage',
        'outbound_internet',
        'disk_space',
        'cache_connection',
        'db_connection',
        'cpu_usage',
      ])
    );
  });

  it('should only run checks that are enabled in the config', async () => {
    const config: Config = {
      checks: {
        memory_usage: true,
        outbound_internet: false,
        disk_space: false,
        cache_connection: false,
        db_connection: false,
        cpu_usage: false,
      },
    } as unknown as Config;

    const result = await healthcheckHandler({}, config);
    const body = JSON.parse(result.body);

    expect(memoryCheck).toHaveBeenCalled();
    expect(egress).not.toHaveBeenCalled();
    expect(disk).not.toHaveBeenCalled();
    expect(cacheConnection).not.toHaveBeenCalled();
    expect(dbConnection).not.toHaveBeenCalled();
    expect(cpuCheck).not.toHaveBeenCalled();

    expect(Object.keys(body.results)).toEqual(['memory_usage']);
  });

  it('should ignore check names not present in the registry', async () => {
    const config: Config = {
      checks: {
        memory_usage: true,
        nonexistent_check: true,
      },
    } as unknown as Config;

    const result = await healthcheckHandler({}, config);
    const body = JSON.parse(result.body);

    expect(Object.keys(body.results)).toEqual(['memory_usage']);
  });

  it('should return status fail when any check fails', async () => {
    (dbConnection as jest.Mock).mockResolvedValue(failResult('db_connection'));

    const result = await healthcheckHandler({}, baseConfig);
    const body = JSON.parse(result.body);

    expect(body.status).toBe(Status.fail);
    expect(body.results.db_connection.status).toBe(Status.fail);
  });

  it('should return status warn when a check warns and none fail', async () => {
    (cpuCheck as jest.Mock).mockResolvedValue(warnResult('cpu_usage'));

    const result = await healthcheckHandler({}, baseConfig);
    const body = JSON.parse(result.body);

    expect(body.status).toBe(Status.warn);
    expect(body.results.cpu_usage.status).toBe(Status.warn);
  });

  it('should prioritize the last fail/warn status encountered while iterating', async () => {
    (cpuCheck as jest.Mock).mockResolvedValue(warnResult('cpu_usage'));
    (dbConnection as jest.Mock).mockResolvedValue(failResult('db_connection'));

    const result = await healthcheckHandler({}, baseConfig);
    const body = JSON.parse(result.body);

    // Both warn and fail present; final status depends on iteration order,
    // but must be either fail or warn, never pass.
    expect([Status.fail, Status.warn]).toContain(body.status);
  });

  it('should call each check function with the config object', async () => {
    await healthcheckHandler({}, baseConfig);

    expect(memoryCheck).toHaveBeenCalledWith(baseConfig);
    expect(egress).toHaveBeenCalledWith(baseConfig);
    expect(disk).toHaveBeenCalledWith(baseConfig);
    expect(cacheConnection).toHaveBeenCalledWith(baseConfig);
    expect(dbConnection).toHaveBeenCalledWith(baseConfig);
    expect(cpuCheck).toHaveBeenCalledWith(baseConfig);
  });

  it('should return application/json type when accept header is missing', async () => {
    const result = await healthcheckHandler({}, baseConfig);
    expect(result.type).toBe('application/json');
  });

  it('should return application/json type when accept header does not include text/html', async () => {
    const result = await healthcheckHandler({ accept: 'application/json' }, baseConfig);
    expect(result.type).toBe('application/json');
  });

  it('should return text/html type when accept header includes text/html', async () => {
    const result = await healthcheckHandler({ accept: 'text/html' }, baseConfig);
    expect(result.type).toBe('text/html');
    expect(result.body).toContain('<!DOCTYPE html>');
  });

  it('should render a pass banner in HTML when all checks pass', async () => {
    const result = await healthcheckHandler({ accept: 'text/html' }, baseConfig);

    expect(result.body).toContain("👌 It's All Good");
    expect(result.body).toContain('#4CAF50');
  });

  it('should render a fail banner in HTML when a check fails', async () => {
    (dbConnection as jest.Mock).mockResolvedValue(failResult('db_connection'));

    const result = await healthcheckHandler({ accept: 'text/html' }, baseConfig);

    expect(result.body).toContain("❌ Something's Wrong");
    expect(result.body).toContain('#F44336');
  });

  it('should render a warn banner in HTML when a check warns', async () => {
    (cpuCheck as jest.Mock).mockResolvedValue(warnResult('cpu_usage'));

    const result = await healthcheckHandler({ accept: 'text/html' }, baseConfig);

    expect(result.body).toContain('#FFC107');
  });

  it('should include check messages and icons in the HTML output', async () => {
    (dbConnection as jest.Mock).mockResolvedValue(failResult('db_connection', 'Database is down'));

    const result = await healthcheckHandler({ accept: 'text/html' }, baseConfig);

    expect(result.body).toContain('Database is down');
    expect(result.body).toContain('❌');
    expect(result.body).toContain('✅');
  });

  it('should display the value in parentheses unless it is true/false', async () => {
    (cpuCheck as jest.Mock).mockResolvedValue({
      componentName: 'cpu_usage',
      status: Status.pass,
      message: 'CPU usage is below 80%',
      value: '45.00%',
      time: 3,
    });

    const result = await healthcheckHandler({ accept: 'text/html' }, baseConfig);

    expect(result.body).toContain('(45.00%)');
  });

  it('should not display parentheses for boolean-like values of true or false', async () => {
    const result = await healthcheckHandler({ accept: 'text/html' }, baseConfig);

    // memory_usage etc default to value 'true', should not render "(true)"
    expect(result.body).not.toContain('(true)');
    expect(result.body).not.toContain('(false)');
  });

  it('should sort checks alphabetically in the HTML output', async () => {
    const result = await healthcheckHandler({ accept: 'text/html' }, baseConfig);

    const cacheIndex = result.body.indexOf('cache_connection');
    const cpuIndex = result.body.indexOf('cpu_usage');
    const dbIndex = result.body.indexOf('db_connection');

    // just verify presence and general structure; sort correctness checked via message order
    const memoryMessageIndex = result.body.indexOf('memory_usage' in {} ? '' : 'message');
    expect(result.body).toContain('checks-list');
  });

  it('should include the time in milliseconds for each check in the HTML output', async () => {
    const result = await healthcheckHandler({ accept: 'text/html' }, baseConfig);

    expect(result.body).toMatch(/\[\d+ms\]/);
  });

  it('should handle an empty checks config gracefully', async () => {
    const config: Config = { checks: {} } as unknown as Config;

    const result = await healthcheckHandler({}, config);
    const body = JSON.parse(result.body);

    expect(body.status).toBe(Status.pass);
    expect(body.results).toEqual({});
  });

  it('should handle accept header with multiple types including text/html', async () => {
    const result = await healthcheckHandler(
      { accept: 'text/plain, text/html, application/json' },
      baseConfig
    );

    expect(result.type).toBe('text/html');
  });

  it('should handle undefined accept header value', async () => {
    const result = await healthcheckHandler({ accept: undefined }, baseConfig);
    expect(result.type).toBe('application/json');
  });
});