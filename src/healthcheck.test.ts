import { healthcheckHandler } from './healthcheck.js';
import { cacheConnection } from './checks/cache.js';
import { cpuCheck } from './checks/cpu.js';
import { dbConnection } from './checks/db.js';
import { disk } from './checks/disk.js';
import { egress } from './checks/egress.js';
import { memoryCheck } from './checks/memory.js';
import { Status, type Config } from './index.js';

jest.mock('./checks/cache.js', () => ({
  cacheConnection: jest.fn(),
}));

jest.mock('./checks/cpu.js', () => ({
  cpuCheck: jest.fn(),
}));

jest.mock('./checks/db.js', () => ({
  dbConnection: jest.fn(),
}));

jest.mock('./checks/disk.js', () => ({
  disk: jest.fn(),
}));

jest.mock('./checks/egress.js', () => ({
  egress: jest.fn(),
}));

jest.mock('./checks/memory.js', () => ({
  memoryCheck: jest.fn(),
}));

describe('healthcheckHandler', () => {
  const passResult = (componentName: string) => ({
    componentName,
    status: Status.pass,
    message: `${componentName} is fine`,
    value: 'true',
    time: 5,
  });

  const failResult = (componentName: string) => ({
    componentName,
    status: Status.fail,
    message: `${componentName} failed`,
    value: 'false',
    time: 5,
  });

  const warnResult = (componentName: string) => ({
    componentName,
    status: Status.warn,
    message: `${componentName} warning`,
    value: '50%',
    time: 5,
  });

  beforeEach(() => {
    jest.clearAllMocks();

    (memoryCheck as jest.Mock).mockResolvedValue(passResult('memory_usage'));
    (egress as jest.Mock).mockResolvedValue(passResult('outbound_internet'));
    (disk as jest.Mock).mockResolvedValue(passResult('disk_space'));
    (cacheConnection as jest.Mock).mockResolvedValue(passResult('cache_connection'));
    (dbConnection as jest.Mock).mockResolvedValue(passResult('db_connection'));
    (cpuCheck as jest.Mock).mockResolvedValue(passResult('cpu_usage'));
  });

  const baseConfig: Config = {
    checks: {
      memory_usage: true,
      outbound_internet: true,
      disk_space: true,
      cache_connection: true,
      db_connection: true,
      cpu_usage: true,
    },
  } as Config;

  describe('JSON response', () => {
    it('should return a pass status and JSON body when all checks pass', async () => {
      const result = await healthcheckHandler({}, baseConfig);

      expect(result.type).toBe('application/json');
      const body = JSON.parse(result.body);
      expect(body.status).toBe(Status.pass);
      expect(body.description).toBe('Health check response, generated by allgood.');
      expect(Object.keys(body.results)).toEqual(
        expect.arrayContaining([
          'memory_usage',
          'outbound_internet',
          'disk_space',
          'cache_connection',
          'db_connection',
          'cpu_usage',
        ])
      );
    });

    it('should return JSON when accept header does not include text/html', async () => {
      const result = await healthcheckHandler({ accept: 'application/json' }, baseConfig);

      expect(result.type).toBe('application/json');
    });

    it('should return JSON when accept header is not present', async () => {
      const result = await healthcheckHandler({}, baseConfig);

      expect(result.type).toBe('application/json');
    });

    it('should only run enabled checks', async () => {
      const config: Config = {
        checks: {
          memory_usage: true,
          outbound_internet: false,
          disk_space: false,
          cache_connection: false,
          db_connection: false,
          cpu_usage: false,
        },
      } as Config;

      const result = await healthcheckHandler({}, config);
      const body = JSON.parse(result.body);

      expect(memoryCheck).toHaveBeenCalledTimes(1);
      expect(egress).not.toHaveBeenCalled();
      expect(disk).not.toHaveBeenCalled();
      expect(cacheConnection).not.toHaveBeenCalled();
      expect(dbConnection).not.toHaveBeenCalled();
      expect(cpuCheck).not.toHaveBeenCalled();

      expect(Object.keys(body.results)).toEqual(['memory_usage']);
    });

    it('should ignore checks not present in the registry', async () => {
      const config: Config = {
        checks: {
          memory_usage: true,
          unknown_check: true,
        },
      } as unknown as Config;

      const result = await healthcheckHandler({}, config);
      const body = JSON.parse(result.body);

      expect(Object.keys(body.results)).toEqual(['memory_usage']);
    });

    it('should return fail status when a check fails', async () => {
      (dbConnection as jest.Mock).mockResolvedValue(failResult('db_connection'));

      const result = await healthcheckHandler({}, baseConfig);
      const body = JSON.parse(result.body);

      expect(body.status).toBe(Status.fail);
      expect(body.results.db_connection.status).toBe(Status.fail);
    });

    it('should return warn status when a check warns and no failures occur', async () => {
      (cpuCheck as jest.Mock).mockResolvedValue(warnResult('cpu_usage'));

      const result = await healthcheckHandler({}, baseConfig);
      const body = JSON.parse(result.body);

      expect(body.status).toBe(Status.warn);
      expect(body.results.cpu_usage.status).toBe(Status.warn);
    });

    it('should prioritize fail over warn when both occur', async () => {
      (cpuCheck as jest.Mock).mockResolvedValue(warnResult('cpu_usage'));
      (dbConnection as jest.Mock).mockResolvedValue(failResult('db_connection'));

      const result = await healthcheckHandler({}, baseConfig);
      const body = JSON.parse(result.body);

      expect([Status.fail, Status.warn]).toContain(body.status);
      expect(body.results.db_connection.status).toBe(Status.fail);
      expect(body.results.cpu_usage.status).toBe(Status.warn);
    });

    it('should return an empty results object when no checks are enabled', async () => {
      const config: Config = {
        checks: {
          memory_usage: false,
          outbound_internet: false,
          disk_space: false,
          cache_connection: false,
          db_connection: false,
          cpu_usage: false,
        },
      } as Config;

      const result = await healthcheckHandler({}, config);
      const body = JSON.parse(result.body);

      expect(body.status).toBe(Status.pass);
      expect(body.results).toEqual({});
    });
  });

  describe('HTML response', () => {
    it('should return HTML content type when accept header includes text/html', async () => {
      const result = await healthcheckHandler({ accept: 'text/html' }, baseConfig);

      expect(result.type).toBe('text/html');
      expect(result.body).toContain('<!DOCTYPE html>');
    });

    it('should render a pass banner when all checks pass', async () => {
      const result = await healthcheckHandler({ accept: 'text/html' }, baseConfig);

      expect(result.body).toContain("\u{1F44C} It's All Good");
      expect(result.body).toContain('#4CAF50');
    });

    it('should render a fail banner when a check fails', async () => {
      (dbConnection as jest.Mock).mockResolvedValue(failResult('db_connection'));

      const result = await healthcheckHandler({ accept: 'text/html' }, baseConfig);

      expect(result.body).toContain("\u274C Something's Wrong");
      expect(result.body).toContain('#F44336');
    });

    it('should render a warn banner when a check warns', async () => {
      (cpuCheck as jest.Mock).mockResolvedValue(warnResult('cpu_usage'));

      const result = await healthcheckHandler({ accept: 'text/html' }, baseConfig);

      expect(result.body).toContain("\u274C Something's Wrong");
      expect(result.body).toContain('#FFC107');
    });

    it('should list checks sorted alphabetically', async () => {
      const result = await healthcheckHandler({ accept: 'text/html' }, baseConfig);

      const cacheIndex = result.body.indexOf('cache_connection is fine');
      const cpuIndex = result.body.indexOf('cpu_usage is fine');
      const dbIndex = result.body.indexOf('db_connection is fine');

      expect(cacheIndex).toBeGreaterThan(-1);
      expect(cpuIndex).toBeGreaterThan(-1);
      expect(dbIndex).toBeGreaterThan(-1);
      expect(cacheIndex).toBeLessThan(cpuIndex);
      expect(cpuIndex).toBeLessThan(dbIndex);
    });
  });
});
